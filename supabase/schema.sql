-- Run this in the Supabase dashboard: SQL Editor -> New query -> Run.
-- Tables for the portfolio tracker, with Row Level Security so each user
-- can only touch their own rows, while admins can manage everyone's.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.holdings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ticker text not null,
  shares numeric not null default 0,
  unique (user_id, ticker)
);

-- Create a profile row automatically when someone signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, username)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1))
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- True when the current user is an admin.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

alter table public.profiles enable row level security;
alter table public.holdings enable row level security;

drop policy if exists "profiles read" on public.profiles;
create policy "profiles read"
  on public.profiles for select
  using (auth.uid() = id or public.is_admin());

drop policy if exists "profiles self update" on public.profiles;
create policy "profiles self update"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- Users must never be able to promote themselves.
revoke update (role) on public.profiles from authenticated;

drop policy if exists "holdings read" on public.holdings;
create policy "holdings read"
  on public.holdings for select
  using (auth.uid() = user_id or public.is_admin());

drop policy if exists "holdings insert" on public.holdings;
create policy "holdings insert"
  on public.holdings for insert
  with check (auth.uid() = user_id or public.is_admin());

drop policy if exists "holdings update" on public.holdings;
create policy "holdings update"
  on public.holdings for update
  using (auth.uid() = user_id or public.is_admin())
  with check (auth.uid() = user_id or public.is_admin());

drop policy if exists "holdings delete" on public.holdings;
create policy "holdings delete"
  on public.holdings for delete
  using (auth.uid() = user_id or public.is_admin());

